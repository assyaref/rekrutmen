    await p.click('.modal .x');
    await p.click('button:has-text("Masuk Admin")');
    await p.waitForSelector('.layout .nav');
    await p.click('.nav a:has-text("Pengaturan")');
    await p.click('.tabs a:has-text("Fitur")');
